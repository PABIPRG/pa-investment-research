#!/usr/bin/env bash
# rc.10 中文逐步彩排脚本：先执行门禁，再输出操作、期望与取证点。
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

bash "$ROOT/scripts/prepare-demo-evolution-data.sh" preflight

cat <<'EOF'

=== rc.10 投研全链路彩排 ===

步骤 1｜画像与持仓
入口：研究工作台 → KYC 风险画像 / 管理持仓
动作：确认画像来源，打开持仓管理并保存演示持仓。
期望：画像、持仓和风险预算分区清晰；画像事实不由 AI 推断。
证据：记录画像标签、持仓数量与工作台风险摘要。

步骤 2｜事件与产业链
入口：研究工作台关联事件 → 产业链
动作：打开一条关联事件，再查看中心公司的上下游关系。
期望：事件可追溯；披露、默认和未披露权重来源明确，默认值不称营收占比。
证据：记录事件标题、中心公司、关系方向和权重来源文案。

步骤 3｜策略候选
入口：事件详情 / 智能分析 → 策略研究
动作：确认投资假设进入策略池。
期望：候选策略显示 candidate，自动创建首次回测；没有人工激活入口。
证据：记录策略标识、来源与首次任务编号。

步骤 4｜首次回测与准入
入口：策略研究 → 选择候选策略 → 回测管理
动作：查看首次回测任务完成状态和验证结果。
期望：任务成功完成后策略自动进入 active；参与状态与验证结论分别显示。
证据：记录任务状态、验证分类、参与状态和报告引用。

步骤 5｜影子任务历史
入口：策略详情 → 影子验证历史 / 全部策略运行记录
动作：切换最近、当前策略和全部策略视图。
期望：任务、逐策略结果、净值证据和报告可互相定位。
证据：记录影子任务编号、交易日、逐策略状态与报告编号。

步骤 6｜自进化四桶
入口：全局导航 → 自进化
动作：检查闭环状态、5 日门槛、正常/观察/升级/淘汰四桶与最近动作。
期望：四桶各有确定性演示证据；结果计数不与生命周期计数混用。
证据：记录 5/5 日、四桶数量、最近动作和闭环开关。

步骤 7｜变异回流候选
入口：自进化 → 候选分组 → 变体详情
动作：打开 demo-promote 的变异子策略。
期望：变异只显示为来源；子策略回流 candidate，并保留母策略关系。
证据：记录子策略标识、来源、参与状态和母策略 demo-promote。

步骤 8｜报告与 AI 解释
入口：顶部投研报告 / 策略详情 AI 解释当前判定
动作：打开对应报告；打开 AI 助理但不发送消息。
期望：报告与页面五维语义一致；AI 输入携带权威上下文并声明不由模型推断。
证据：记录报告五维字段和 AI 预填提示。

步骤 9｜响应式与恢复
入口：自进化及上述关键页面
动作：检查 1440×900 浅色与 390×844；暂时停止隔离后端后刷新，再恢复。
期望：无页面级横向溢出；关键控件可操作；错误可行动且重试恢复。
证据：记录 viewport、scrollWidth、错误提示与恢复后的状态。

彩排完成条件：RC10-E2E-16 与 RC10-E2E-17 的全部证据进入 UAT 记录，且隔离服务已停止。
EOF
